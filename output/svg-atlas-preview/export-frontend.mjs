// Regenerate the approved drawings, then package them for the single-file Tavern frontend.
import './generate.mjs';
import fs from 'node:fs';
import path from 'node:path';
import { gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { prepareAtlasSymbols } from './prepare-symbols.mjs';

const dir = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(dir, '../../src/灯火通明/atlas/generated');
fs.mkdirSync(target, { recursive: true });
const shell = fs.readFileSync(path.join(dir, 'preview-shell.html'), 'utf8');
const css = shell.match(/<style>([\s\S]*?)<\/style>/)[1]
  .replace(':root {', ':host {').replace('body {', '.atlas-shell {')
  .replace('height: 100dvh;', 'height: 100%;');
const body = shell.match(/<body>([\s\S]*?)<script>/)[1]
  .replace(/<footer[\s\S]*?<\/footer>/, '');
const embeddedCss = fs.readFileSync(path.resolve(target, '../embedded.css'), 'utf8');
const catalog = [];
for (const [realm, page, drawing] of [
  ['surface', 'index.html', 'shanhai-atlas.svg'],
  ['underworld', 'underworld.html', 'underworld-atlas.svg'],
  ['sky', 'sky.html', 'sky-atlas.svg'],
]) {
  const html = fs.readFileSync(path.join(dir, page), 'utf8');
  const data = JSON.parse(html.match(/const atlasData = (.*);\r?\n/)[1]);
  data.realm = realm;
  // The game view fits geography instead of the print border and title margins.
  if (realm === 'surface') data.overview = { x: 140, y: 62, w: 1320, h: 812 };
  if (realm === 'underworld') data.overview = { x: 130, y: 108, w: 1570, h: 1080 };
  const svg = fs.readFileSync(path.join(dir, drawing), 'utf8');
  if (/<(?:image|script|foreignObject)\b/i.test(svg)) throw new Error(`${drawing}: expected pure SVG`);
  const prepared = prepareAtlasSymbols(svg);
  data.symbols = prepared.symbols;
  const markup = `<style>${css}\n${embeddedCss}</style><div class="atlas-shell" tabindex="0">${body.replace('<!-- ATLAS_SVG -->', prepared.markup)}</div>`;
  const packed = gzipSync(JSON.stringify({ markup, data }), { level: 9 }).toString('base64');
  fs.writeFileSync(path.join(target, `${realm}.ts`), `// Generated by output/svg-atlas-preview/export-frontend.mjs; do not edit.\nexport default '${packed}';\n`);
  for (const [kind, list] of Object.entries({ region: data.regions, city: data.capitals, site: data.sites, sect: data.sects, array: data.arrays, portal: data.portals })) {
    for (const { id, domain, x, y, view, key } of list || []) catalog.push({ id, domain, x, y, view, key, realm, kind });
  }
  console.log(`${realm}: ${(packed.length / 1024 / 1024).toFixed(2)} MB embedded, ${svg.length.toLocaleString()} SVG characters`);
}
fs.writeFileSync(path.join(target, 'catalog.ts'), `// Generated by export-frontend.mjs.\nimport type { AtlasAnchor } from '../types';\nexport default ${JSON.stringify(catalog, null, 2)} satisfies AtlasAnchor[];\n`);
const geography = fs.readFileSync(path.join(dir, 'surface-geography.json'), 'utf8');
fs.writeFileSync(path.join(target, 'geography.ts'), `// Generated from the drawn region outlines; do not edit.\nexport default ${geography} as Record<string, [number, number][]>;\n`);

// Compile the existing, visually verified controller into a scoped module. No eval,
// iframe, remote asset URL, or Tavern document/hash listener is used at runtime.
let script = shell.match(/<script>([\s\S]*?)<\/script>/)[1];
script = script.replace('const atlasData = /* ATLAS_DATA */;', '')
  .replace('openFragment();window.addEventListener(\'hashchange\',openFragment);', '')
  .replace(/    function openFragment\(\)\{[\s\S]*?\n    \}/, '');
const prelude = `// Generated from preview-shell.html by export-frontend.mjs. Edit the preview controller at its source.
/* eslint-disable */
import { bindAtlasIntegration } from '../integration';
import { createAtlasCamera } from '../camera';
import { prepareAtlasLayout } from '../layout';
export function mountAtlas(root, atlasData, options) {
  prepareAtlasLayout(root, atlasData);
  const owner = root.ownerDocument;
  const frames = new Set(), observers = [], events = new AbortController();
  const requestAnimationFrame = callback => {
    const id = globalThis.requestAnimationFrame(time => { frames.delete(id); callback(time); });
    frames.add(id); return id;
  };
  const ResizeObserver = class extends globalThis.ResizeObserver {
    constructor(callback) { super(callback); observers.push(this); }
  };
  const document = {
    body: root.querySelector('.atlas-shell'), documentElement: root.host,
    querySelector: selector => root.querySelector(selector),
    querySelectorAll: selector => root.querySelectorAll(selector),
    getElementById: id => root.getElementById(id),
    createElement: tag => owner.createElement(tag),
    addEventListener: (type, listener) => root.addEventListener(type, listener, { signal: events.signal }),
    get fullscreenElement() { return owner.fullscreenElement; },
    exitFullscreen: () => owner.exitFullscreen(),
  };
`;
const epilogue = `
  return bindAtlasIntegration({ root, svg, ready: camera.ready, data: atlasData, showDetail, closeDetail, focusView, setSkyLevel, scheduleLabels,
    cleanup: () => { camera.dispose(); events.abort(); observers.forEach(o => o.disconnect()); frames.forEach(id => globalThis.cancelAnimationFrame(id)); }
  }, options);
}
`;
fs.writeFileSync(path.join(target, 'runtime.js'), prelude + script + epilogue);
