// Publish only atlas files using an isolated Git index; the current branch and staging area stay independent.
/* eslint-disable import-x/no-nodejs-modules */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = 'assets/atlas/manifest.json';
const manifest = JSON.parse(fs.readFileSync(path.join(root, manifestPath), 'utf8'));
const files = Object.values(manifest.realms).map(({ file, integrity }) => {
  if (!/^(surface|underworld|sky)\.[a-f0-9]{20}\.atlas$/.test(file)) throw new Error('Invalid atlas resource name');
  const relative = 'assets/atlas/' + file;
  const hash = createHash('sha256')
    .update(fs.readFileSync(path.join(root, relative)))
    .digest('base64');
  if (integrity !== 'sha256-' + hash) throw new Error(`Atlas checksum mismatch: ${file}`);
  return relative;
});
if (manifest.formatVersion !== 1 || files.length !== 3) throw new Error('Expected three versioned atlas resources');

const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'denghuo-atlas-'));
const index = path.join(scratch, 'index');
const env = { ...process.env, GIT_INDEX_FILE: index };
const git = (...args) =>
  execFileSync('git', args, { cwd: root, env, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }).trim();
try {
  const remote = git('remote', 'get-url', 'origin')
    .replace(/\.git$/, '')
    .replace(/\/$/, '');
  if (!remote.endsWith('/' + manifest.repository) && !remote.endsWith(':' + manifest.repository)) {
    throw new Error('Atlas repository does not match origin');
  }
  const ref = 'refs/heads/atlas-assets';
  const previous = git('ls-remote', '--heads', 'origin', ref).split(/\s/)[0];
  if (previous) {
    git('fetch', '--no-tags', 'origin', ref);
    git('read-tree', previous);
  } else git('read-tree', '--empty');
  // Add named files only, retaining older versions already published on the asset branch.
  git('add', '--', manifestPath, ...files);
  const tree = git('write-tree');
  const unchanged = previous && tree === git('rev-parse', previous + '^{tree}');
  const commit = unchanged
    ? previous
    : git(
        'commit-tree',
        tree,
        ...(previous ? ['-p', previous] : []),
        '-m',
        'Publish versioned three-realm atlas resources',
      );
  if (!unchanged) git('push', 'origin', commit + ':' + ref);
  const release = path.join(root, 'src/灯火通明/atlas/generated/release.ts');
  const releaseSource = `// Generated by tools/publish-atlas.mjs after a successful resource publication.\nexport default '${commit}';\n`;
  if (!fs.existsSync(release) || fs.readFileSync(release, 'utf8') !== releaseSource) {
    fs.writeFileSync(release, releaseSource);
  }
  console.log(`Atlas release: ${commit}`);
  console.log(`https://cdn.jsdelivr.net/gh/${manifest.repository}@${commit}/assets/atlas/`);
} finally {
  for (const file of [index, index + '.lock']) {
    if (fs.existsSync(file)) fs.unlinkSync(file);
  }
  fs.rmdirSync(scratch);
}
